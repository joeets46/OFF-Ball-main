def test_every_row_fits_the_ddl(world, recorded):
    rows = [("match", m.row()) for m in world.matches]
    rows += [("player", p.row()) for p in world.players]
    rows += [("match_squad", s.row()) for s in world.squads]
    for recording, frames in recorded.values():
        capture = recording.capture
        rows.append(("capture", capture.row()))
        rows += [("capture_period", r) for r in capture.period_rows()]
        rows.append(("frame", frames[0].row(capture)))
        rows += [("player_frame_position", r) for r in frames[0].position_rows(capture)]
    problems = [p for table, row in rows for p in schema.check_row(table, row)]
    assert not problems, problems


def test_schema_reads_the_ddl():
    assert set(schema.tables()) == {
        "pitch_zone", "off_ball_action_type", "match", "player", "match_squad",
        "capture", "capture_period", "frame", "player_frame_position",
        "off_ball_action", "off_ball_action_zone",
        "_change_log",   # generated by 70_audit.sql
    }
    assert "ball_carrier_player_id" in schema.columns("frame")
    assert "frame_id" not in schema.required("player_frame_position")   # linked
    assert "match_id" in schema.required("capture")


