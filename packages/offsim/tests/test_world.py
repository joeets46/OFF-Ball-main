def test_eleven_per_side_and_the_sub_comes_on_at_half_time(world, recorded):
    for recording, frames in recorded.values():
        match = recording.capture.match
        side = {s.player_id: s.team_side for s in world.squad(match)}
        for f in frames:
            assert Counter(side[p] for p, *_ in f.positions) == {"H": 11, "A": 11}
        for team_side, (_, sub_id) in world.substitutions[match.match_id].items():
            on = {f.period for f in frames if any(p == sub_id for p, *_ in f.positions)}
            assert on == {2}


def test_frame_count_and_numbering(recorded):
    for recording, frames in recorded.values():
        capture = recording.capture
        assert len(frames) == 2 * capture.frames_per_period
        assert [f.frame_number for f in frames] == list(range(len(frames)))
        for period in capture.period_rows():
            in_period = [f.frame_number for f in frames if f.period == period["period"]]
            assert (in_period[0], in_period[-1]) == (period["start_frame_number"],
                                                     period["end_frame_number"])
        assert frames[capture.frames_per_period].period_clock_ms == 0


def test_gps_has_no_ball(recorded):
    for recording, frames in recorded.values():
        if recording.capture.method == "gps":
            assert all(f.ball is None and f.ball_carrier_player_id is None for f in frames)


def test_ball_carrier_is_on_the_possessing_side(world, recorded):
    for recording, frames in recorded.values():
        side = {s.player_id: s.team_side for s in world.squad(recording.capture.match)}
        for f in frames:
            if f.ball_carrier_player_id is not None:
                assert side[f.ball_carrier_player_id] == f.possession_side


# -- physics and coordinates -----------------------------------------------------

def test_nobody_outruns_a_footballer(recorded):
    top = max(s for _, frames in recorded.values() for f in frames for *_, s in f.positions)
    assert top <= 10.5


def test_positions_normalise_onto_the_pitch(world, recorded):
    """Undoing unit, origin and direction puts everyone on the pitch, both halves."""
    for recording, frames in recorded.values():
        capture = recording.capture
        side = {s.player_id: s.team_side for s in world.squad(capture.match)}
        for f in frames[:: max(1, len(frames) // 50)]:
            for p, x, y, _ in f.positions:
                xn, yn = _normalise(capture, f, x, y, side[p])
                assert -5 <= xn <= 105 and -5 <= yn <= 105


def test_goalkeepers_change_ends_at_half_time(world, recorded):
    """Each keeper stays in their own defensive end once normalised, but swaps vendor x sign."""
    for recording, frames in recorded.values():
        capture = recording.capture
        keepers = {s.player_id: s.team_side for s in world.squad(capture.match)
                   if s.is_goalkeeper and s.is_starter}
        sign = {}
        for f in (frames[10], frames[capture.frames_per_period + 10]):
            for p, x, y, _ in f.positions:
                if p in keepers:
                    xn, _ = _normalise(capture, f, x, y, keepers[p])
                    assert xn < 25
                    sign.setdefault(p, set()).add(x > 0)
        assert all(s == {True, False} for s in sign.values())


def test_centimetre_captures_are_a_hundred_times_larger(world, recorded):
    spans = {}
    for recording, frames in recorded.values():
        c = recording.capture
        if c.method == "optical":
            spans[c.coordinate_unit] = max(abs(x) for f in frames[:50] for _, x, _, _ in f.positions)
    assert spans["cm"] > 30 * spans["m"]


